import { ZodError } from "zod";

/**
 * Joins a zod error's issues into one message that names each failing path,
 * e.g. "calendar.weekNumbering: Required; resources.2.code: Duplicate code".
 */
export function describeZodIssues(error: ZodError): string {
  return error.issues
    .map((issue) => {
      const path = issue.path.length > 0 ? issue.path.join(".") : "(root)";
      return `${path}: ${issue.message}`;
    })
    .join("; ");
}
