// English names for months and weekdays in display text. Fixed tables rather
// than toLocaleString, so the text is the same on every server and browser
// whatever its locale or ICU data.

import { Weekday } from "./types";

/** Month names, January first, so month M is MONTH_NAMES[M - 1]. */
export const MONTH_NAMES = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
] as const;

/** Three-letter month names, "Jan" first, indexed like MONTH_NAMES. */
export const MONTH_ABBREVIATIONS = [
  "Jan",
  "Feb",
  "Mar",
  "Apr",
  "May",
  "Jun",
  "Jul",
  "Aug",
  "Sep",
  "Oct",
  "Nov",
  "Dec",
] as const;

/** "MONDAY" becomes "Monday". */
export function weekdayName(weekday: Weekday): string {
  return weekday.charAt(0) + weekday.slice(1).toLowerCase();
}
